//! What TF2 lends other games' apps (`chimera_core::game_parts`): its
//! twelve guns by class (the Scattergun and the Engineer's Shotgun
//! shotguns, the Rocket Launcher, Grenade and Stickybomb Launchers
//! launchers, the Minigun a heavy gun, the Pistol a pistol, the SMG and
//! the Syringe Gun SMGs, the Sniper Rifle a sniper, the Revolver a heavy
//! pistol, the Flame Thrower a flamethrower;
//! `weapons`), and its movement (`movement::ID`: Source's with TF2's
//! classes), which makes it `playable` in a gun game's ladder: a rung of a
//! TF2 gun makes its holder TF2's and the gun's class (`classes`: its body,
//! speed and health), and its HUD is this game's id (`ui`).
//!
//! No map is claimed (`PARTS.maps` is empty): its maps enter an app's
//! automatic pool from the install or the asset store the machine has
//! (`auto::InstalledMaps`), as its pool rules allow (data/map_pool.toml:
//! every map denied but the koth_, cp_ and ctf_ maps chosen for a
//! free-for-all, with why), drawn by its measurements (data/
//! map_fitness.toml, the `map_fitness` tool's) for the players present
//! (`add_map_pool`, from the bundle's `party_sim`). So a machine without
//! TF2 is offered none; any map plays when asked by id (`tf2:ctf_2fort`).
//! Its maps play as a free-for-all: every team's spawn points, the spawn
//! rooms open to all (`maps::free_for_all_doors`).

use chimera_core::game_data::GameData;
use chimera_core::game_parts::{GameParts, GunClass, GunPart};

use super::weapons::{
    FLAMETHROWER, GRENADE_LAUNCHER, MINIGUN, PISTOL_SCOUT, REVOLVER, ROCKET_LAUNCHER, SCATTERGUN, SHOTGUN, SMG, SNIPER_RIFLE,
    STICKY_LAUNCHER, SYRINGE_GUN,
};

const fn gun(id: &'static str, class: GunClass) -> GunPart {
    GunPart { id, class }
}

/// TF2's parts.
pub static PARTS: GameParts = GameParts {
    game: super::GAME,
    guns: &[
        gun(SCATTERGUN, GunClass::Shotgun),
        gun(ROCKET_LAUNCHER, GunClass::Launcher),
        gun(SHOTGUN, GunClass::Shotgun),
        gun(MINIGUN, GunClass::Heavy),
        gun(PISTOL_SCOUT, GunClass::Pistol),
        gun(SMG, GunClass::Smg),
        gun(SNIPER_RIFLE, GunClass::Sniper),
        gun(REVOLVER, GunClass::HeavyPistol),
        gun(GRENADE_LAUNCHER, GunClass::Launcher),
        gun(STICKY_LAUNCHER, GunClass::Launcher),
        gun(FLAMETHROWER, GunClass::Flamethrower),
        gun(SYRINGE_GUN, GunClass::Smg),
    ],
    knife: Some(super::weapons::KNIFE),
    movement: Some(super::movement::ID),
    characters: None,
    hud: Some(super::GAME),
    maps: &[],
    announcer: None,
    match_won_sound: None,
    match_lost_sound: None,
    music: false,
    cues: None,
    scaffold: false,
};

/// Its map pool's rules (data/map_pool.toml: every installed map denied
/// but those chosen for a free-for-all; `chimera_sim::minigame::map_fit`).
pub const POOL_RULES: GameData = chimera_core::game_data!("data/map_pool.toml");

/// Its maps' measurements (data/map_fitness.toml, generated by the
/// `map_fitness` tool's `--write`): a rotation draws by them for the
/// players present.
pub const MAP_FITNESS: GameData = chimera_core::game_data!("data/map_fitness.toml");

/// Its pool rules and measurements registered (`map_fit::MapPoolAppExt`).
pub fn add_map_pool(app: &mut bevy::app::App) {
    use chimera_sim::minigame::map_fit::MapPoolAppExt;
    app.add_map_pool_rules(super::GAME, "tf2 data/map_pool.toml", &POOL_RULES)
        .add_map_fitness(super::GAME, "tf2 data/map_fitness.toml", &MAP_FITNESS);
}
