//! What Halo lends other games' apps (`chimera_core::game_parts`): its
//! maps and its nine held guns (M2 and M3 of docs/plans/active/halo-ce.md:
//! the assault rifle a rifle, the pistol a heavy pistol, the plasma rifle
//! and the needler SMGs, the shotgun a shotgun, the sniper rifle a sniper,
//! the plasma pistol a pistol, the rocket launcher a launcher, by their
//! weight in a ladder's variety; not the flamethrower: its flame ends
//! 2.5 WU out, so it cannot hurt at the 10 to 20 m a ladder's power curve
//! scores at, and no stock map places it: multiplayer_rules.md 5.3 makes
//! it a rocket launcher)
//! with its movement (`movement::ID`), so a gun game's automatic ladder
//! deals them as rungs. Holding one makes the character Halo's where the
//! identity follows the weapon (`chimera_sim::identity`): Halo's movement,
//! and with it its vitality and shield (`vitality`'s wear), and its HUD
//! (`ui::hud`). The Spartan body (`body`) and the guns' view and held
//! models (`view`, from the donor map on another game's map).
//!
//! And one grenade rung: Halo's grenades are not a held weapon but a count
//! thrown on the grenade button beside the gun in hand (`weapons::grenades`),
//! so Halo lends a part of class `grenade` of its own, the frag grenade's
//! rung (`weapons::rung`: the empty pistol in hand, frags on the grenade
//! button), which the ladder's grenade band deals as it deals the other
//! games' grenades. And the Hunter's cannon (`weapons::rung::HUNTER_RUNG`),
//! a launcher whose holder is always the Hunter: dealt by a drawn ladder
//! only with `halo_ce:campaign_bodies` 1 (`campaign::own_guns_drawn`).
//!
//! No map is claimed (`PARTS.maps` is empty): a map enters an app's pool
//! only from the disc image the machine holds (`auto::InstalledMaps`),
//! as its pool rules allow (data/map_pool.toml: the maps a game of other
//! games' movement can't play yet are denied, with why), drawn by its
//! measurements (data/map_fitness.toml, the `map_fitness` tool's). So
//! without the disc image no Halo map is offered anywhere, and with it the
//! allowed ones are (`add_map_pool`, from the bundle's `sim`).

use chimera_core::game_parts::{GameParts, GunClass, GunPart};

use super::weapons::{
    rung::{FRAG_RUNG, HUNTER_RUNG},
    ASSAULT_RIFLE, NEEDLER, PISTOL, PLASMA_PISTOL, PLASMA_RIFLE, ROCKET_LAUNCHER, SHOTGUN, SNIPER_RIFLE,
};

const fn gun(id: &'static str, class: GunClass) -> GunPart {
    GunPart { id, class }
}

/// Halo's parts.
pub static PARTS: GameParts = GameParts {
    game: super::GAME,
    guns: &[
        gun(ASSAULT_RIFLE, GunClass::Rifle),
        gun(PISTOL, GunClass::HeavyPistol),
        gun(PLASMA_RIFLE, GunClass::Smg),
        gun(SHOTGUN, GunClass::Shotgun),
        gun(SNIPER_RIFLE, GunClass::Sniper),
        gun(ROCKET_LAUNCHER, GunClass::Launcher),
        gun(NEEDLER, GunClass::Smg),
        gun(PLASMA_PISTOL, GunClass::Pistol),
        gun(FRAG_RUNG, GunClass::Grenade),
        gun(HUNTER_RUNG, GunClass::Launcher),
    ],
    knife: None,
    movement: Some(super::movement::ID),
    characters: Some("halo_ce:spartan"),
    hud: Some(super::GAME),
    maps: &[],
    announcer: None,
    match_won_sound: None,
    match_lost_sound: None,
    music: false,
    cues: None,
};

/// Its map pool's rules (data/map_pool.toml: the installed maps an
/// automatic pool leaves out, with why; `chimera_sim::minigame::map_fit`).
pub const POOL_RULES: chimera_core::game_data::GameData = chimera_core::game_data!("data/map_pool.toml");

/// Its maps' measurements (data/map_fitness.toml, generated by the
/// `map_fitness` tool's `--write`): a rotation draws by them for the
/// players present.
pub const MAP_FITNESS: chimera_core::game_data::GameData = chimera_core::game_data!("data/map_fitness.toml");

/// Its arena slices (data/arena_slices.toml: parts of its big maps the
/// party apps may play as whole ones, `chimera_sim::minigame::arena`).
pub const ARENA_SLICES: chimera_core::game_data::GameData = chimera_core::game_data!("data/arena_slices.toml");

/// Its pool rules, measurements and arena slices registered
/// (`map_fit::MapPoolAppExt`).
pub fn add_map_pool(app: &mut bevy::app::App) {
    use chimera_sim::minigame::map_fit::MapPoolAppExt;
    app.add_map_pool_rules(super::GAME, "halo_ce data/map_pool.toml", &POOL_RULES)
        .add_map_fitness(super::GAME, "halo_ce data/map_fitness.toml", &MAP_FITNESS)
        .add_arena_slices(super::GAME, "halo_ce data/arena_slices.toml", &ARENA_SLICES);
}

/// What an app of several games needs for Halo's guns: its movement
/// registered (not made the match's), its vitality and damage seam, and
/// its weapons, each once.
pub fn add_guns(app: &mut bevy::app::App) {
    if !app.is_plugin_added::<super::weapons::HaloWeaponsPlugin>() {
        super::movement::register(app);
        app.add_plugins((super::vitality::VitalityPlugin, super::damage::DamagePlugin, super::weapons::HaloWeaponsPlugin, super::fx::HaloFxPlugin));
        app.add_plugins(super::weapons::systems::BatteryRoundsPlugin);
    }
}
