//! What Halo lends other games' apps (`chimera_core::game_parts`): its
//! maps only, for now. Its guns, movement, characters and HUD come with
//! their specs (weapons.md, movement.md, hud.md), so it is not `playable`
//! in a gun game's ladder; its maps are played with the other games'
//! players, movement and guns (docs/plans/active/halo-ce.md, M1).
//!
//! No map is claimed (`PARTS.maps` is empty): a map enters an app's pool
//! only from the disc image the machine holds (`auto::InstalledMaps`),
//! as its pool rules allow (data/map_pool.toml: the maps a game of other
//! games' movement can't play yet are denied, with why), drawn by its
//! measurements (data/map_fitness.toml, the `map_fitness` tool's). So
//! without the disc image no Halo map is offered anywhere, and with it the
//! allowed ones are (`add_map_pool`, from the bundle's `sim`).

use chimera_core::game_parts::GameParts;

/// Halo's parts.
pub static PARTS: GameParts = GameParts {
    game: super::GAME,
    guns: &[],
    knife: None,
    movement: None,
    characters: Some("halo_ce:spartan"),
    hud: None,
    maps: &[],
    announcer: None,
    match_won_sound: None,
    match_lost_sound: None,
    music: false,
    cues: None,
};

/// Its map pool's rules (data/map_pool.toml: the installed maps an
/// automatic pool leaves out, with why; `chimera_sim::minigame::map_fit`).
pub const POOL_RULES: &str = include_str!("../../data/map_pool.toml");

/// Its maps' measurements (data/map_fitness.toml, generated by the
/// `map_fitness` tool's `--write`): a rotation draws by them for the
/// players present.
pub const MAP_FITNESS: &str = include_str!("../../data/map_fitness.toml");

/// Its pool rules and measurements registered (`map_fit::MapPoolAppExt`).
pub fn add_map_pool(app: &mut bevy::app::App) {
    use chimera_sim::minigame::map_fit::MapPoolAppExt;
    app.add_map_pool_rules(super::GAME, "halo_ce data/map_pool.toml", POOL_RULES)
        .add_map_fitness(super::GAME, "halo_ce data/map_fitness.toml", MAP_FITNESS);
}
