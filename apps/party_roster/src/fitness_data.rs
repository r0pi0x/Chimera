//! The map-pool fitness files (`games/<game>/data/map_fitness.toml`)
//! written from a `map_fitness` sweep's CSV (docs/plans/active/
//! map-pool-fitness.md): per map its area, sight, spawn points and spots
//! and its wander times, which an automatic gun game's pool draws by
//! (`chimera_sim::minigame::map_fit`). `write` writes only the games the
//! CSV has rows of: a sweep of some games leaves the others' files as
//! they are (it once emptied them).

use std::path::{Path, PathBuf};

/// The player counts whose wander times the CSV and the files carry.
pub const WANDER_PLAYERS: [usize; 3] = [4, 8, 12];

/// What `write` did with one game's file.
#[derive(Clone, Debug, PartialEq)]
pub struct Written {
    /// The game.
    pub game: String,
    /// Its `games/<game>/data/map_fitness.toml`.
    pub path: PathBuf,
    /// The maps written, or None: the CSV has no rows of the game and the
    /// file was left as it is.
    pub maps: Option<usize>,
}

/// Each of `games`' `games/<game>/data/map_fitness.toml` under `repo`
/// from the sweep's CSV text `csv`, for the games with rows in it; the
/// others' files are not touched.
pub fn write(csv: &str, repo: &Path, games: &[String], speed: f32) -> Result<Vec<Written>, String> {
    let mut out = Vec::new();
    for game in games {
        let path = repo.join("games").join(game).join("data").join("map_fitness.toml");
        let (doc, n) = fitness_toml(csv, game, speed);
        if n == 0 {
            out.push(Written { game: game.clone(), path, maps: None });
            continue;
        }
        std::fs::write(&path, doc).map_err(|e| format!("{}: {e}", path.display()))?;
        out.push(Written { game: game.clone(), path, maps: Some(n) });
    }
    Ok(out)
}

/// `game`'s rows of a sweep's CSV as its data/map_fitness.toml, and how
/// many maps.
pub fn fitness_toml(csv: &str, game: &str, speed: f32) -> (String, usize) {
    let mut lines = csv.lines();
    let header: Vec<&str> = lines.next().unwrap_or_default().split(',').collect();
    let col = |row: &[&str], name: &str| -> String {
        header.iter().position(|h| *h == name).and_then(|i| row.get(i)).map_or(String::new(), |v| v.to_string())
    };
    let num = |v: String| -> f32 { v.parse().unwrap_or(0.0) };
    let mut rows: Vec<(String, String)> = Vec::new();
    for line in lines {
        let row: Vec<&str> = line.split(',').collect();
        if col(&row, "game") != game {
            continue;
        }
        let name = col(&row, "map").to_ascii_lowercase();
        let area = num(col(&row, "area_m2")).max(0.0);
        let loads = col(&row, "loads") == "true" && area > 0.0;
        let wander: Vec<String> = WANDER_PLAYERS
            .iter()
            .map(|n| format!("{n} = {:.1}", num(col(&row, &format!("wander_{n}_s")))))
            .collect();
        let mut t = format!("[maps.{name}]\n");
        if !loads {
            t.push_str("loads = false\n");
        }
        t.push_str(&format!(
            "area_m2 = {area:.0}\nsight_m = {:.1}\nspot_area_m2 = {:.0}\nspawns = {}\nspots = {}\nspots_off = {}\nstuck = {}\nwander_s = {{ {} }}\n",
            num(col(&row, "sight_m")),
            num(col(&row, "spot_area_m2")).max(0.0),
            num(col(&row, "spawns")) as u32,
            num(col(&row, "spots")) as u32,
            num(col(&row, "spots_off")) as u32,
            num(col(&row, "stuck")) as u32,
            wander.join(", ")
        ));
        rows.push((name, t));
    }
    rows.sort();
    rows.dedup_by(|a, b| a.0 == b.0);
    let mut out = format!(
        "# {game}'s maps measured for an automatic gun game's pool, generated by the\n\
         # map_fitness tool (`--write`; docs/plans/active/map-pool-fitness.md): edit\n\
         # data/map_pool.toml instead. Per map: its walkable area (m2), mean sight (m),\n\
         # the area its spawn spots cover, its spawn points, spawn spots, those off\n\
         # the map and those a player is stuck in, and its wander times at 4/8/12\n\
         # players (s; read by chimera_sim::minigame::map_fit, which works them out\n\
         # again from area and sight at any count).\n\
         speed_mps = {speed}\n"
    );
    let n = rows.len();
    for (_, t) in rows {
        out.push('\n');
        out.push_str(&t);
    }
    (out, n)
}
