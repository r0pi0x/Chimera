//! The generated doc lists: `docs/modules.md` (one line per source file,
//! from the first sentence of its `//!` doc), the generated block of
//! `docs/tech-debt.md` (one line per "Known shortcuts" paragraph, from its
//! first sentence), and `docs/agent-index.md` (every heading of the
//! hand-written `docs/*.md` with the line it starts at). A feature edits only
//! its own file's `//!` doc; the lists are rebuilt, never edited by hand, so
//! parallel branches stop conflicting on them (architecture review, T5).
//!
//! Regenerate with `cargo run -q -p repo_checks --bin docs_index`; with
//! `--check` it only reports stale files. The architecture test
//! `generated_docs_are_fresh` fails when the committed files differ.
//!
//! The index exists so a reader opens the section it needs instead of the
//! file: `performance.md` is 2,000 lines and 45,354 tokens, its headings and
//! first sentences are 1,512 (2026-10-30).
//!
//! Reading a doc: the `//!` lines of a file, split into paragraphs at empty
//! ones. A file's summary is the first sentence of its first paragraph; a
//! shortcut is a paragraph that starts with "Known shortcuts", with a
//! leading "(docs/tech-debt.md ...)" and colon dropped.
//!
//! Known shortcuts: A sentence ends at the first full stop and space outside
//! backticks and parentheses that does not follow a short abbreviation
//! (e.g, vs); a doc whose first sentence breaks elsewhere gets an odd summary, fixed by
//! rewording its first line. Summaries longer than the limits are cut at a
//! word with "...". Files under `tests/` are left out of the module list.

use std::fs;
use std::path::{Path, PathBuf};

/// Folders searched for Rust files, in the order of the module list.
const ROOTS: &[&str] = &[
    "chimera", "source", "lithtech", "games", "apps", "tools", "checks", "src",
];
/// Longest summary in the module list, in characters.
pub const MODULE_LINE: usize = 150;
/// Longest shortcut sentence in the debt list, in characters.
pub const DEBT_LINE: usize = 150;

/// Start and end of the generated part of `docs/tech-debt.md`.
pub const DEBT_BEGIN: &str = "<!-- generated by `cargo run -q -p repo_checks --bin docs_index`: do not edit below -->";
pub const DEBT_END: &str = "<!-- end of generated entries -->";

/// The command that rebuilds the generated docs.
pub const COMMAND: &str = "cargo run -q -p repo_checks --bin docs_index";

/// The generated index of the hand-written docs' headings.
pub const INDEX_FILE: &str = "docs/agent-index.md";
/// Longest section line in that index, in characters.
pub const INDEX_LINE: usize = 140;

/// A file's `//!` doc as paragraphs (each joined into one line).
fn doc_paragraphs(code: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    for line in code.lines() {
        let Some(rest) = line.trim_start().strip_prefix("//!") else {
            continue;
        };
        let rest = rest.trim();
        if rest.is_empty() {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
        } else {
            if !cur.is_empty() {
                cur.push(' ');
            }
            cur.push_str(rest);
        }
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// The first sentence of `text`, cut at `limit` characters on a word.
fn first_sentence(text: &str, limit: usize) -> String {
    let chars: Vec<char> = text.chars().collect();
    let (mut ticks, mut depth) = (0usize, 0i32);
    let mut end = chars.len();
    for (i, &c) in chars.iter().enumerate() {
        match c {
            '`' => ticks += 1,
            '(' if ticks % 2 == 0 => depth += 1,
            ')' if ticks % 2 == 0 => depth -= 1,
            '.' if ticks % 2 == 0 && depth <= 0 && chars.get(i + 1).is_none_or(|n| n.is_whitespace()) => {
                let word: String = chars[..i].iter().rev().take_while(|c| !c.is_whitespace()).collect();
                let word: String = word.chars().rev().collect();
                let abbreviation = matches!(
                    word.to_ascii_lowercase().as_str(),
                    "e.g" | "i.e" | "vs" | "etc" | "approx" | "cf" | "no" | "fig"
                );
                if !abbreviation {
                    end = i;
                    break;
                }
            }
            _ => {}
        }
    }
    let s: String = chars[..end].iter().collect();
    let s = s.trim().trim_end_matches('.');
    if s.chars().count() <= limit {
        return s.to_string();
    }
    let cut: String = s.chars().take(limit.saturating_sub(3)).collect();
    let cut = cut.rsplit_once(' ').map_or(cut.as_str(), |(head, _)| head);
    format!("{}...", cut.trim_end_matches([',', ';', ':', ' ']))
}

/// The text of a "Known shortcuts" paragraph after its lead-in.
fn shortcut_text(paragraph: &str) -> Option<&str> {
    let rest = paragraph.strip_prefix("Known shortcuts")?;
    let rest = match rest.strip_prefix(" (docs/tech-debt.md") {
        // The pointer, possibly with a remark, up to its closing parenthesis.
        Some(inner) => {
            let mut depth = 1;
            let mut close = None;
            for (i, c) in inner.char_indices() {
                match c {
                    '(' => depth += 1,
                    ')' => {
                        depth -= 1;
                        if depth == 0 {
                            close = Some(i);
                            break;
                        }
                    }
                    _ => {}
                }
            }
            &inner[close? + 1..]
        }
        None => rest,
    };
    let rest = rest.trim_start_matches(':').trim();
    (!rest.is_empty()).then_some(rest)
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        let name = e.file_name().to_string_lossy().into_owned();
        if p.is_dir() {
            if name != "target" && !name.starts_with('.') {
                rust_files(&p, out);
            }
        } else if name.ends_with(".rs") {
            out.push(p);
        }
    }
}

/// Every Rust file under the roots, as repository-relative paths, sorted.
fn sources(root: &Path) -> Vec<String> {
    let mut files = Vec::new();
    for r in ROOTS {
        rust_files(&root.join(r), &mut files);
    }
    let mut rel: Vec<String> = files
        .iter()
        .filter_map(|f| f.strip_prefix(root).ok())
        .map(|f| f.to_string_lossy().replace('\\', "/"))
        .collect();
    rel.sort();
    rel
}

/// The heading a path is listed under: its crate folder.
fn group(path: &str) -> String {
    let parts: Vec<&str> = path.split('/').collect();
    match parts[0] {
        "chimera" | "source" | "lithtech" | "games" | "apps" | "tools" if parts.len() > 2 => {
            format!("{}/{}", parts[0], parts[1])
        }
        _ => parts[0].to_string(),
    }
}

/// What the committed docs should hold: the whole `docs/modules.md`, the
/// generated entries of `docs/tech-debt.md` (without its markers) and the
/// whole `docs/agent-index.md`.
pub struct Generated {
    pub modules: String,
    pub debt: String,
    pub index: String,
}

pub fn generate(root: &Path) -> Generated {
    let mut modules = String::from(
        "# Modules\n\n\
         Generated from each file's `//!` doc (its first sentence): do not edit.\n\
         Change a file's `//!` doc with the code, then run\n\
         `cargo run -q -p repo_checks --bin docs_index` (the architecture test\n\
         `generated_docs_are_fresh` fails when this file is stale). Files under\n\
         `tests/` are not listed. The layers and crates are in ARCHITECTURE.md.\n",
    );
    let mut debt = String::new();
    let mut current = String::new();
    for path in sources(root) {
        let Ok(code) = fs::read_to_string(root.join(&path)) else {
            continue;
        };
        let paragraphs = doc_paragraphs(&code);
        for p in &paragraphs {
            if let Some(text) = shortcut_text(p) {
                debt.push_str(&format!("- `{path}`: {}\n", first_sentence(text, DEBT_LINE)));
            }
        }
        if path.split('/').any(|c| c == "tests") {
            continue;
        }
        let Some(first) = paragraphs.first() else { continue };
        if first.starts_with("Known shortcuts") {
            continue;
        }
        let g = group(&path);
        if g != current {
            modules.push_str(&format!("\n## {g}\n\n"));
            current = g;
        }
        modules.push_str(&format!("- `{path}`: {}\n", first_sentence(first, MODULE_LINE)));
    }
    Generated {
        modules,
        debt,
        index: index(root),
    }
}

/// The doc index: every heading of the hand-written `docs/*.md`, with the line
/// it starts at and the first sentence under it.
fn index(root: &Path) -> String {
    let mut out = String::from(
        "# Docs index\n\n\
         Generated from the headings of `docs/*.md`: do not edit. Each entry is the\n\
         line a section starts at, then the first sentence under it, so a reader\n\
         opens the section it needs instead of the whole file. Regenerate with\n\
         `cargo run -q -p repo_checks --bin docs_index`; the architecture test\n\
         `generated_docs_are_fresh` fails when this file is stale. The per-file\n\
         module list is `docs/modules.md`.\n",
    );
    for path in doc_files(root) {
        let Ok(text) = fs::read_to_string(root.join(&path)) else {
            continue;
        };
        let sections = sections(&text);
        if sections.is_empty() {
            continue;
        }
        out.push_str(&format!("\n## {path}\n\n"));
        for (line, heading, summary) in sections {
            if summary.is_empty() {
                out.push_str(&format!("- {line}: {heading}\n"));
            } else {
                out.push_str(&format!("- {line}: {heading} | {summary}\n"));
            }
        }
    }
    out
}

/// The hand-written docs: every top-level `docs/*.md`, sorted. The module list
/// and this index are themselves lists, and `docs/plans/` changes with every
/// task.
fn doc_files(root: &Path) -> Vec<String> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(root.join("docs")) else {
        return out;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if path.is_file() && name.ends_with(".md") && name != "modules.md" && name != "agent-index.md" {
            out.push(format!("docs/{name}"));
        }
    }
    out.sort();
    out
}

/// A markdown file's headings outside code fences, as (line, heading, first
/// sentence of the prose under it). A `#` line inside a fence is a comment in
/// an example, not a section.
fn sections(text: &str) -> Vec<(usize, String, String)> {
    let lines: Vec<&str> = text.lines().collect();
    let mut out = Vec::new();
    let mut fence = false;
    let mut i = 0;
    while i < lines.len() {
        if is_fence(lines[i]) {
            fence = !fence;
            i += 1;
            continue;
        }
        if fence {
            i += 1;
            continue;
        }
        let Some(heading) = heading_text(lines[i]) else {
            i += 1;
            continue;
        };
        let mut prose = String::new();
        let mut quoted = false;
        let mut j = i + 1;
        while j < lines.len() {
            if is_fence(lines[j]) {
                quoted = !quoted;
            } else if !quoted && heading_text(lines[j]).is_some() {
                break;
            } else if !quoted && is_prose(lines[j]) {
                if !prose.is_empty() {
                    prose.push(' ');
                }
                prose.push_str(lines[j].trim());
                if prose.chars().count() > INDEX_LINE * 2 {
                    break;
                }
            } else if !prose.is_empty() {
                break;
            }
            j += 1;
        }
        let summary = if prose.is_empty() {
            String::new()
        } else {
            first_sentence(&prose, INDEX_LINE)
        };
        out.push((i + 1, heading.to_string(), summary));
        i = j.max(i + 1);
    }
    out
}

fn is_fence(line: &str) -> bool {
    let text = line.trim_start();
    text.starts_with("```") || text.starts_with("~~~")
}

/// `line`'s heading text when it is one, levels 1 to 3.
fn heading_text(line: &str) -> Option<&str> {
    let text = line.trim_end();
    let hashes = text.chars().take_while(|c| *c == '#').count();
    if hashes == 0 || hashes > 3 {
        return None;
    }
    let rest = text[hashes..].strip_prefix(' ')?.trim();
    (!rest.is_empty()).then_some(rest)
}

/// Whether a line is prose a summary can be taken from: not a list, table,
/// tag, quote, image, rule or indented example.
fn is_prose(line: &str) -> bool {
    let text = line.trim();
    let Some(first) = text.chars().next() else {
        return false;
    };
    !matches!(
        first,
        '|' | '<' | '!' | '[' | '*' | '+' | '-' | '>' | '#' | '`' | '=' | '_' | '~'
    ) && !first.is_ascii_digit()
}

/// `existing` (the committed tech-debt.md) with its generated block replaced
/// by `entries`; `None` when the markers are missing.
pub fn with_debt_block(existing: &str, entries: &str) -> Option<String> {
    let begin = existing.find(DEBT_BEGIN)?;
    let end = existing.find(DEBT_END)?;
    (begin < end).then(|| format!("{}{DEBT_BEGIN}\n{entries}{}", &existing[..begin], &existing[end..]))
}

/// The files that differ from what the sources say, as (path, new content).
pub fn stale(root: &Path) -> Result<Vec<(&'static str, String)>, String> {
    let g = generate(root);
    let mut out = Vec::new();
    // Line endings normalised: a Windows clone may check docs out with CRLF.
    let read = |p: &str| {
        fs::read_to_string(root.join(p))
            .unwrap_or_default()
            .replace("\r\n", "\n")
    };
    if read("docs/modules.md") != g.modules {
        out.push(("docs/modules.md", g.modules));
    }
    if read(INDEX_FILE) != g.index {
        out.push((INDEX_FILE, g.index));
    }
    let debt = read("docs/tech-debt.md");
    let new = with_debt_block(&debt, &g.debt)
        .ok_or_else(|| format!("docs/tech-debt.md lacks the markers {DEBT_BEGIN:?} and {DEBT_END:?}"))?;
    if new != debt {
        out.push(("docs/tech-debt.md", new));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sentences_stop_at_a_full_stop_outside_code_and_parens() {
        assert_eq!(
            first_sentence("The VFS (see fs.rs. Not here) and `a. b` core. More.", 100),
            "The VFS (see fs.rs. Not here) and `a. b` core"
        );
        assert_eq!(
            first_sentence("Slots, e.g. movement. Next.", 100),
            "Slots, e.g. movement"
        );
        assert_eq!(first_sentence("one two three four five six", 15), "one two...");
    }

    #[test]
    fn shortcut_paragraphs_drop_their_lead_in() {
        assert_eq!(
            shortcut_text("Known shortcuts (docs/tech-debt.md): Ours. Rest."),
            Some("Ours. Rest.")
        );
        assert_eq!(
            shortcut_text("Known shortcuts (docs/tech-debt.md; a (nested) remark): Ours."),
            Some("Ours.")
        );
        assert_eq!(shortcut_text("Known shortcuts: Ours."), Some("Ours."));
        assert_eq!(
            shortcut_text("Known shortcuts (the spec's reading): Ours."),
            Some("(the spec's reading): Ours.")
        );
        assert_eq!(shortcut_text("Something else."), None);
    }

    #[test]
    fn docs_are_paragraphs_of_inner_comments() {
        let p = doc_paragraphs("//! One\n//! two.\n//!\n//! Three.\nfn f() {}\n");
        assert_eq!(p, ["One two.", "Three."]);
    }

    #[test]
    fn the_debt_block_is_replaced_in_place() {
        let doc = format!("head\n{DEBT_BEGIN}\nold\n{DEBT_END}\ntail\n");
        let new = with_debt_block(&doc, "- new\n").unwrap();
        assert_eq!(new, format!("head\n{DEBT_BEGIN}\n- new\n{DEBT_END}\ntail\n"));
    }

    #[test]
    fn headings_in_code_fences_are_not_sections() {
        let doc = "# Title\n\nprose here.\n\n```sh\n# not a heading\n```\n\n## Real\n\nIts sentence.\n";
        let s = sections(doc);
        assert_eq!(s.len(), 2);
        assert_eq!(s[0], (1, "Title".to_string(), "prose here".to_string()));
        assert_eq!(s[1], (9, "Real".to_string(), "Its sentence".to_string()));
    }

    #[test]
    fn a_section_without_prose_still_gets_an_entry() {
        let s = sections("## Table\n\n| a | b |\n|---|---|\n");
        assert_eq!(s, [(1, "Table".to_string(), String::new())]);
    }
}
